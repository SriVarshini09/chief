#!/usr/bin/env python
"""Fill the DEMO Google account with the fictional Chief story data.

Default is a DRY RUN: it prints exactly what would be created and touches nothing. Writing needs --apply,
--i-am-using-a-demo-account, a demo-looking CHIEF_DEMO_GMAIL address, and a typed confirmation.

What it creates (everything is invented: people and companies live on *.example domains):
  1. About ten emails, appended to INBOX over IMAP/SSL (imap.gmail.com) with an app password, left unread.
     Date headers are relative to the day you run it. One email is written as an injection attempt aimed at an
     AI assistant, so the demo can show it being flagged and ignored.
  2. Calendar events through Chief's own LiveTools.create_event (Composio): the story calendar from
     chief/tools/mock.py for the past 14 days and the next 7. Every event carries MARKER in its description.
  3. data/sample_health.csv (SAMPLE data, generated by chief.health) anchored to today.

It never deletes or modifies existing mail or events, never prints or logs the app password, and never takes it
on the command line (env var CHIEF_DEMO_APP_PASSWORD only). See docs/demo-account.md.
"""


# ----------------------------------------------------------------------------------------------- output
class Out:
    """All printing goes through here so a secret can never reach the screen, even by accident."""

    def __init__(self, write: Callable[[str], None] = print, secrets: tuple[str, ...] = ()):
        self._write = write
        self.secrets = [s for s in secrets if s]

    def __call__(self, text: str = "") -> None:
        for s in self.secrets:
            text = text.replace(s, "***")
        self._write(text)


# ----------------------------------------------------------------------------------------------- emails
@dataclass
class SeedMail:
    key: str
    sender: str
    subject: str
    date: datetime  # aware, local
    body: str
    message_id: str

    def to_message(self, to: str) -> EmailMessage:
        msg = EmailMessage(policy=policy.SMTP)
        msg["From"] = self.sender
        msg["To"] = to
        msg["Subject"] = self.subject
        msg["Date"] = format_datetime(self.date)
        msg["Message-ID"] = self.message_id
        msg["X-Chief-Demo-Seed"] = "1"
        msg.set_content(self.body)
        return msg


def _message_id(key: str) -> str:
    # No date in the id on purpose: running again on another day must still be recognised as the same message.
    return f"<{MARKER}-{key}@seed.chief-demo.example>"



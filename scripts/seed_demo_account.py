# ----------------------------------------------------------------------------------------------- calendar
@dataclass
class SeedEvent:
    key: str
    title: str
    start: datetime  # naive local, like the rest of Chief
    end: datetime
    attendees: list[str]

    @property
    def description(self) -> str:
        who = f" Attendees: {', '.join(self.attendees)}." if self.attendees else ""
        return f"{MARKER} key={self.key}. Fictional demo data, safe to delete.{who}"


def _plan(weekday: int) -> list[tuple[int, str, list[str]]]:
    return HEAVY if weekday in health.HEAVY_WEEKDAYS else LIGHT if weekday in (2, 4) else []


def build_events(now: datetime) -> list[SeedEvent]:
    """Same story as MockTools: Mon/Tue/Thu heavy, Wed/Fri light, weekends empty, plus Dana's external meeting."""
    now = now.replace(tzinfo=None)
    out: list[SeedEvent] = []
    for offset in range(-PAST_DAYS, FUTURE_DAYS + 1):
        day = (now + timedelta(days=offset)).replace(hour=0, minute=0, second=0, microsecond=0)
        for hour, title, who in _plan(day.weekday()):
            start = day.replace(hour=hour)
            out.append(SeedEvent(f"ev-{day:%Y%m%d}-{hour:02d}", title, start, start + timedelta(minutes=60), _addresses(who)))
    for offset in range(0, FUTURE_DAYS):  # first non-heavy day from today, as in mock.py
        day = (now + timedelta(days=offset)).replace(hour=16, minute=30, second=0, microsecond=0)
        if day.weekday() not in health.HEAVY_WEEKDAYS:
            out.append(SeedEvent(f"ev-ext-acme-{day:%Y%m%d}", "Acme pricing review", day, day + timedelta(minutes=60), [DANA, SAM]))
            break
    return sorted(out, key=lambda e: e.start)


def _addresses(names: list[str]) -> list[str]:
    known = {"dana": DANA, "sam": SAM}
    return [known[n] for n in names if n in known]  # "team", "maya", ... are labels in the mock, not addresses


# ----------------------------------------------------------------------------------------------- guards
def looks_like_demo(address: str) -> bool:
    local, _, domain = address.strip().lower().partition("@")
    return "demo" in local and domain in GMAIL_DOMAINS


def check_env(env: Any, *, apply: bool, flag: bool) -> tuple[str | None, str | None]:
    """Returns (address, error). A set address that does not look like the demo account is refused even in a dry
    run. Applying also needs the flag, the address and the app password."""
    address = (env.get(ENV_GMAIL) or "").strip()
    if address and not looks_like_demo(address):
        return None, (
            f"{ENV_GMAIL} does not look like the demo account (need a gmail.com address whose name contains 'demo', "
            "for example chief.demo.2026@gmail.com). Refusing to run."
        )
    if not apply:
        return address or None, None
    if not flag:
        return None, f"--apply also needs {DEMO_FLAG}. Refusing to run."
    if not address:
        return None, f"--apply needs {ENV_GMAIL} set to the demo mailbox address. Refusing to run."
    if not (env.get(ENV_PASSWORD) or "").strip():
        return None, f"--apply needs {ENV_PASSWORD} set (a Google app password). Refusing to run."
    return address, None


# ----------------------------------------------------------------------------------------------- planning output
def print_plan(out: Out, mails: list[SeedMail], events: list[SeedEvent], to: str, selected: set[str], now: datetime) -> None:
    if "mail" in selected:
        out(f"== Emails: {len(mails)} to append to {MAILBOX} of {to} (unread; skipped if the Message-ID is already there)")
        for m in mails:
            out(f"-- {m.key}")
            out(f"   From: {m.sender}")
            out(f"   To: {to}")
            out(f"   Subject: {m.subject}")
            out(f"   Date: {format_datetime(m.date)}")
            out(f"   Message-ID: {m.message_id}")
            for line in m.body.rstrip().splitlines():
                out(f"   | {line}")
    if "calendar" in selected:
        out(f"== Calendar: {len(events)} events via LiveTools.create_event (skipped if marker/key or same title+time exists)")
        for e in events:
            extra = f"  attendees: {', '.join(e.attendees)}" if e.attendees else ""
            out(f"-- {e.start:%a %Y-%m-%d %H:%M}-{e.end:%H:%M}  {e.title}  [{e.key}]{extra}")
        out(f"   Every event description contains '{MARKER}'. Attendees are listed in the description only (create_event has no attendee field).")
    if "sleep" in selected:
        out(f"== Sleep CSV: would write {CSV_PATH.relative_to(ROOT)} (SAMPLE data from chief.health, anchored to {now:%Y-%m-%d})")


# ----------------------------------------------------------------------------------------------- apply steps
def seed_mail(out: Out, mails: list[SeedMail], address: str, password: str, imap_factory: Callable[[str], Any]) -> int:
    """APPEND only. Calls login, select, search, append, logout; never store/delete/expunge/copy."""
    failures = 0
    try:
        imap = imap_factory(IMAP_HOST)
        imap.login(address, password)
    except (imaplib.IMAP4.error, OSError) as exc:
        out(f"Mail: could not log in to {IMAP_HOST} ({type(exc).__name__}). Check the app password and that IMAP is enabled.")
        return len(mails)
    try:
        imap.select(MAILBOX)
        for m in mails:
            typ, data = imap.search(None, "HEADER", "Message-ID", m.message_id)
            if typ == "OK" and data and data[0]:
                out(f"Mail: skip {m.key} (already in {MAILBOX})")
                continue
            raw = m.to_message(address).as_bytes()
            typ, _ = imap.append(MAILBOX, "", imaplib.Time2Internaldate(m.date), raw)  # empty flags = unread
            if typ == "OK":
                out(f"Mail: added {m.key}")
            else:
                failures += 1
                out(f"Mail: FAILED {m.key} ({typ})")
    except (imaplib.IMAP4.error, OSError) as exc:
        failures += 1
        out(f"Mail: stopped early ({type(exc).__name__}).")
    finally:
        try:
            imap.logout()
        except Exception:  # noqa: BLE001  (closing a dead connection is best effort)
            pass
    return failures


def seed_calendar(out: Out, events: list[SeedEvent], tools: Any, now: datetime) -> int:
    """create_event only. Existing events are read once to skip duplicates and are never touched."""
    first, last = events[0].start, events[-1].end
    try:
        existing = tools.list_events(first - timedelta(days=1), last + timedelta(days=1))
    except Exception as exc:  # noqa: BLE001
        out(f"Calendar: could not read existing events ({type(exc).__name__}); not creating anything.")
        return len(events)
    have_keys = {e.description for e in existing}
    have_slots = {(e.title, e.start) for e in existing}
    failures = added = 0
    for ev in events:
        if any(f"key={ev.key}." in d for d in have_keys) or (ev.title, ev.start) in have_slots:
            out(f"Calendar: skip {ev.key} (already there)")
            continue
        try:
            tools.create_event(ev.title, ev.start.isoformat(), ev.end.isoformat(), ev.description)
            added += 1
            out(f"Calendar: added {ev.key} {ev.title} {ev.start:%a %m-%d %H:%M}")
        except Exception as exc:  # noqa: BLE001
            failures += 1
            out(f"Calendar: FAILED {ev.key} ({type(exc).__name__})")
    out(f"Calendar: {added} created.")
    return failures


def seed_sleep(out: Out, now: datetime, path: Path = CSV_PATH) -> int:
    if path.exists():
        first = path.read_text(encoding="utf-8").splitlines()[:1]
        if first != [CSV_HEADER]:
            out(f"Sleep: {path} exists and is not a sample file; left alone.")
            return 0
    health.write_sample_csv(path, now.replace(tzinfo=None))
    out(f"Sleep: wrote {path}. This is SAMPLE data generated by chief.health, not real health data.")
    return 0


# ----------------------------------------------------------------------------------------------- main
def make_live_tools() -> Any:
    from chief.config import Config  # loads .env, only when really applying
    from chief.tools.live import LiveTools

    return LiveTools(Config.from_env())


def main(
    argv: list[str] | None = None,
    *,
    env: Any = None,
    now: datetime | None = None,
    imap_factory: Callable[[str], Any] | None = None,
    tools_factory: Callable[[], Any] | None = None,
    input_fn: Callable[[str], str] = input,
    write: Callable[[str], None] = print,
    csv_path: Path = CSV_PATH,
) -> int:
    p = argparse.ArgumentParser(description="Seed the DEMO Google account with fictional Chief story data (dry run by default).")
    p.add_argument("--apply", action="store_true", help="really create the emails/events/CSV (default: dry run)")
    p.add_argument(DEMO_FLAG, dest="demo_ok", action="store_true", help="confirm the target is a demo account")
    p.add_argument("--only", action="append", choices=["mail", "calendar", "sleep"], help="limit to one part (repeatable)")
    args = p.parse_args(argv)

    if env is None:
        if args.apply:  # .env is read only when really applying
            try:
                from dotenv import load_dotenv

                load_dotenv()
            except ImportError:
                pass
        env = os.environ
    password = (env.get(ENV_PASSWORD) or "").replace(" ", "").strip()
    out = Out(write, secrets=(password, env.get(ENV_PASSWORD) or ""))

    address, error = check_env(env, apply=args.apply, flag=args.demo_ok)
    if error:
        out(error)
        return 2
    selected = set(args.only or ["mail", "calendar", "sleep"])
    now = now or datetime.now()
    to = address or PLACEHOLDER_ADDRESS
    mails, events = build_emails(now), build_events(now)

    out(f"Chief demo seed: {'APPLY' if args.apply else 'DRY RUN (nothing will be created)'}; today is {now:%A %Y-%m-%d}.")
    if not address:
        out(f"({ENV_GMAIL} is not set; showing {PLACEHOLDER_ADDRESS} as the recipient.)")
    print_plan(out, mails, events, to, selected, now)
    if not args.apply:
        out("")
        out(f"Dry run only. To write: set {ENV_GMAIL} and {ENV_PASSWORD}, then run with --apply {DEMO_FLAG}.")
        return 0

    out("")
    out(f"This will ADD the items above to {address} (and Composio's calendar). Nothing existing is deleted or changed.")
    try:
        typed = input_fn(f"Type the demo address ({address}) to continue, anything else cancels: ").strip()
    except (EOFError, KeyboardInterrupt):
        typed = ""
    if typed.lower() != address.lower():
        out("Cancelled. Nothing was created.")
        return 1

    failures = 0
    if "mail" in selected:
        failures += seed_mail(out, mails, address, password, imap_factory or imaplib.IMAP4_SSL)
    if "calendar" in selected:
        try:
            tools = (tools_factory or make_live_tools)()
        except Exception as exc:  # noqa: BLE001
            detail = re.sub(r"\s+", " ", str(exc))[:160]
            out(f"Calendar: could not set up Chief's live tools ({type(exc).__name__}: {detail}).")
            failures += len(events)
        else:
            failures += seed_calendar(out, events, tools, now)
    if "sleep" in selected:
        failures += seed_sleep(out, now, csv_path)
    out("Done." if not failures else f"Done with {failures} problem(s); see above. Running again is safe.")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
